const UPPER = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ';

/** Characters in atlas order (RetroFont reads them left to right, top to bottom). */
export const FONT_CHARS = `${Object.keys(G).join('')}${UPPER.toLowerCase()}`;

function glyphFor(ch: string): readonly string[] {
	return G[ch] ?? G[ch.toUpperCase()] ?? G[' '] ?? [];
}

/** Renders the font atlas: white glyphs with a dark drop shadow (tint multiplies both). */
export function renderFontAtlas(color: number, shadow: number): PixelCanvas {
	const rows = Math.ceil(FONT_CHARS.length / CHARS_PER_ROW);
	const c = new PixelCanvas(CHARS_PER_ROW * CELL_W, rows * CELL_H);
	[...FONT_CHARS].forEach((ch, i) => {
		const ox = (i % CHARS_PER_ROW) * CELL_W;
		const oy = Math.floor(i / CHARS_PER_ROW) * CELL_H;
		const glyph = glyphFor(ch);
		const on = (x: number, y: number) => glyph[y]?.[x] === '#';
		for (let y = 0; y < GLYPH_H; y++) {
			for (let x = 0; x < GLYPH_W; x++) {
				if (on(x, y) && !on(x + 1, y + 1)) c.px(ox + x + 1, oy + y + 1, shadow);
			}
		}
		for (let y = 0; y < GLYPH_H; y++) {
			for (let x = 0; x < GLYPH_W; x++) if (on(x, y)) c.px(ox + x, oy + y, color);
		}
	});
	return c;
}

/** Width in px of a single-line string rendered with the pixel font at scale 1. */
export function textWidth(text: string): number {
	return text.length * CELL_W;
}
