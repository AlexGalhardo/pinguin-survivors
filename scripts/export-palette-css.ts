import { PALETTE, toCss } from '../src/config/palette';

const kebab = (s: string): string => s.replace(/([a-z\d])([A-Z])/g, '$1-$2').toLowerCase();

/** Tailwind v4 `@theme` block with every PALETTE color as `--color-<kebab-name>`. */
export function paletteCss(): string {
	const vars = Object.entries(PALETTE)
		.map(([name, value]) => `\t--color-${kebab(name)}: ${toCss(value)};`)
		.join('\n');
	return `/* Generated by scripts/export-palette-css.ts from src/config/palette.ts; do not edit. */\n@theme {\n${vars}\n}\n`;
}

if (import.meta.main) {
	// The game UI and the site (SDD-008) share the same tokens.
	for (const path of ['../src/ui/palette.css', '../site/src/styles/palette.css']) {
		const out = new URL(path, import.meta.url);
		await Bun.write(out, paletteCss());
		console.log(`wrote ${out.pathname}`);
	}
}
