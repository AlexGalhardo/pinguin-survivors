/**
 * Freezes the jsfxr SFX presets: generates each preset with a seeded RNG, applies the
 * tweaks of src/data/sfx.ts and prints the concrete synth params (paste into src/data/sfx-params.ts).
 * Usage: bun scripts/gen-sfx.ts > src/data/sfx-params.ts
 */
import { sfxr } from 'jsfxr';
import { SFX_PRESETS } from '../src/data/sfx';
import { Rng } from '../src/logic/rng';

const rng = new Rng(20260925);
Math.random = () => rng.next();

const out: Record<string, Record<string, number>> = {};
for (const [key, preset] of Object.entries(SFX_PRESETS)) {
	const p = sfxr.generate(preset.algorithm) as unknown as Record<string, number>;
	if (preset.freqMul) p.p_base_freq = Math.min(1, (p.p_base_freq ?? 0) * preset.freqMul);
	if (preset.decayMul) p.p_env_decay = Math.min(1, (p.p_env_decay ?? 0) * preset.decayMul);
	if (preset.sustainMul)
		p.p_env_sustain = Math.min(1, (p.p_env_sustain ?? 0) * preset.sustainMul);
	p.sound_vol = 0.5;
	const clean: Record<string, number> = {};
	for (const [k, v] of Object.entries(p)) {
		if (typeof v === 'number') clean[k] = Math.round(v * 10000) / 10000;
	}
	out[key] = clean;
}
console.log(
	'/** Frozen jsfxr synth params (generated by scripts/gen-sfx.ts; tweak by hand or in sfxr.me). */',
);
console.log(
	`export const SFX_PARAMS: Record<string, Record<string, number>> = ${JSON.stringify(out, null, '\t')};`,
);
